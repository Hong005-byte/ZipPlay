@"# ZipPlay 自定义主题完整说明

这份文档是给两种读者准备的：想仔细看规则的人，或者一个 AI（把这整份文档贴给 AI，跟它说你想要
什么风格——比如""帮我做一个赛博朋克风格、主色是粉紫色的主题""——它可以照着下面的字段规则帮你生成
