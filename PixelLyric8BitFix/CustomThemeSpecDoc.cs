## 顶层字段

| 字段 | 必填 | 类型 | 说明 |
|---|---|---|---|
| `name` | 是 | 字符串 | 主题名字，显示在皮肤选择器和「已保存的客制化主题」列表里 |
| `font` | 否 | 字符串 | 字体名，系统里得真的装了这个字体（不填默认 `Segoe UI`）；内置皮肤常用的几款：`Segoe UI` / `Segoe UI Light` / `Segoe UI Semibold` / `Georgia` / `Consolas` / `Lucida Console`，这几个 Windows 都自带 |
| `colors` | 是 | 对象 | 见下面「颜色」 |
| `background` | 是 | 对象 | 见下面「背景」 |
| `icon` | 是 | 对象 | 见下面「图标」（主图标，固定贴在歌词框上方那条装饰栏） |
| `animation` | 是 | 对象 | 见下面「动画」 |
| `layers` | 否 | 数组 | 见下面「额外装饰层」，最多 2 个，是叠加在主图标之上的额外小装饰，不是替换 |

## 颜色 colors

全部是 #RRGGBB 或带透明度的 #AARRGGBB 格式（比如 #F9C784、#B32A1F40）。

| 字段 | 必填 | 说明 |
|---|---|---|
| `title` | 是 | 歌曲标题文字颜色 |
| `artist` | 是 | 艺人名 / 时间文字颜色 |
| `accent` | 是 | 强调色——进度条、图标发光默认颜色、Mini 小方块边框都用它 |
| `lyric` | 是 | 歌词文字颜色 |
| `glow` | 否 | 歌词发光颜色，不填就用 `accent` |
| `glowBlur` | 否 | 歌词发光的模糊半径，数字，不填默认 3，填 0 就是没有发光效果 |
| `lyricBoxBg` | 是 | 歌词框背景色（建议带透明度，比如 #B32A1F40，纯色框会显得很生硬） |
| `lyricBoxBorder` | 是 | 歌词框边框颜色 |

## 背景 background

| 字段 | 必填 | 说明 |
|---|---|---|
| `type` | 是 | ""solid""（纯色）或 ""gradient""（渐变） |
| `direction` | 否 | ""vertical"" 或 ""diagonal""，只有 type 是 gradient 时才有意义 |
| `stops` | 是 | 颜色数组，至少 1 个；gradient 至少要 2 个才有渐变效果，建议 2~4 个 |

## 图标 icon（主图标）

字符网格 + 调色板，两种都要填：

- `rows`：字符串数组，每个字符代表一个像素格，`.` 固定是透明。行数和每行宽度都必须在 4~64 之间
  （两个方向各自独立判断，不要求正方形，比如 8 行 x 16 列的长条形也行）。每一行必须一样宽，
  宽度不一致会报错。实际展示位（Mini 小方块、装饰栏）也就 20~52px 上下，网格开太大细节会被压掉
  看不出来，图省事的话 8x8 就够。
- `palette`：一个对象，key 是网格里用到的单字符（除了 `.`），value 是这个字符对应的十六进制颜色。
  就算图标全是 `.`（空白），也要留一个空对象 {}，不能整个字段不写。

## 动画 animation

`type` 是这几种之一，也可以用 **+** 连起来同时挂好几招（比如 ""pulse+sway""）：

| 招式 | 效果 |
|---|---|
| `pulse` | 呼吸发光，平缓的明暗循环 |
| `twinkle` | 图标本体渐隐渐现，比 pulse 幅度更大 |
| `drift` | 飘过整张卡片（横向） |
| `fall` | 飘落整张卡片（纵向，带一点左右摇摆） |
| `bob` | 原地上下浮动 |
| `sway` | 以底部为轴心左右轻摆 |
| `spin` | 匀速转圈 |
| `flicker` | 不规则明暗跳动，比 pulse/twinkle 更""毛躁"" |

**组合规则**：

- 两招控制的是同一个属性的话，后一个会直接盖掉前一个，等于只有后一个生效——不是报错，是""选了也
  白选""。哪几招是同一属性：`pulse`/`flicker` 都是控制发光度；`sway`/`spin` 都是控制角度；
  `bob`/`fall` 都是控制纵向位置。挑组合的时候尽量选控制不同属性的招式，才能真的叠加出效果
  （比如 pulse+sway、twinkle+bob+spin）。
- **drift/fall 不能跟别的招式组合，也不能互相组合**——这两招是整张卡片飘过/飘落的专属轨道，跟
  主图标固定显示在装饰栏这件事结构上冲突，只能单独用（""drift"" 或 ""fall""，不能是 ""drift+pulse""）。
  **这条限制只对主图标（顶层 animation）生效，layers 里的额外装饰层没有这个限制，可以自由组合
  全部 8 招。**

其它字段：

| 字段 | 必填 | 说明 |
|---|---|---|
| `duration` | 否 | 秒，数字，必须大于 0；不填就用每种招式各自的默认时长 |
| `musicReactive` | 否 | true/false，不填默认 false。开了之后，这份动画（不管选的是哪招/哪个组合）的播放速度会跟着系统正在播的音乐响度/鼓点实时变化，跟设置页「皮肤音乐律动」总开关是同一套机制，那个开关关了这里勾了也不生效 |
| `sensitivity` | 否 | ""low"" / ""medium"" / ""high""，不填默认 medium。只在 musicReactive 为 true 时才有意义，决定这份动画对响度/鼓点变化""反应多强""——low 声音大变化也比较克制，high 反过来会被小声音放得更明显 |

## 额外装饰层 layers（可选，最多 2 个）

数组，每个元素是一个对象：

| 字段 | 必填 | 说明 |
|---|---|---|
| `anchor` | 是 | 贴在卡片哪个角：""top-left"" / ""top-right"" / ""bottom-left"" / ""bottom-right"" |
| `icon` | 是 | 跟主图标同一套字段形状（rows + palette） |
| `animation` | 是 | 跟主图标同一套字段形状，**但没有""drift/fall 不能组合""这条限制** |

