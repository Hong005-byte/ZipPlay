## 图标 icon（主图标）

字符网格 + 调色板，两种都要填：

- `rows`：字符串数组，每个字符代表一个像素格，`.` 固定是透明。行数和每行宽度都必须在 4~64 之间
  （两个方向各自独立判断，不要求正方形，比如 8 行 x 16 列的长条形也行）。每一行必须一样宽，
  宽度不一致会报错。实际展示位（Mini 小方块、装饰栏）也就 20~52px 上下，网格开太大细节会被压掉
  看不出来，图省事的话 8x8 就够。
- `palette`：一个对象，key 是网格里用到的单字符（除了 `.`），value 是这个字符对应的十六进制颜色。
  就算图标全是 `.`（空白），也要留一个空对象 {}，不能整个字段不写。

### 逐帧动画 frames（可选）——让图标真的动起来

不是靠旋转/缩放这些变换，是像 Minecraft 皮肤那个会走路的角色一样，画好几张图交替显示，看起来
像是在走路/扇翅膀/眨眼。可选字段，不填就还是 `rows` 那一张静态图，完全不影响老写法：

- `frames`：一个数组，每一项是一份跟 `rows` 长得一模一样的字符网格（同样的行数/宽度范围 4~64、
  同样每行要等宽）。**帧数不设上限**，想画几帧就画几帧，2 帧（比如走路只需要「左脚在前/右脚在前」
  两张）或者 20 帧的更细腻动画都可以。**唯一的硬性要求：所有帧必须是完全相同的尺寸**（行数和宽度
  都要跟第 1 帧一致）——尺寸不一致的话切换的时候图标会跳着缩放/错位，看着是「抖」不是「动」，校验会
  直接拒掉。给了 `frames` 之后 `rows` 会被忽略（渲染只认 `frames`），`rows` 这时候不用填。
- `frameDuration`：可选，数字（秒），每帧播放多久才切到下一帧，不填默认 0.25（跟 Minecraft 角色
  走路换腿的节奏差不多）。`musicReactive` 开着的话，换帧节奏也会跟着系统正在播的音乐响度/鼓点变——
  跟这份动画本身的 `sensitivity` 是同一套调法。

示例（一个 2 帧的简易走路循环）：

```json
""icon"": {
  ""palette"": { ""#"": ""#F9C784"" },
  ""frames"": [
    [""........"", "".######."", "".######."", ""..#..#..""],
    [""........"", "".######."", "".######."", "".#....#.""]
  ],
  ""frameDuration"": 0.3
}
```

> 目前只有**主图标**（贴在歌词框上方那条装饰栏的那个）支持逐帧动画。Mini 小方块图标、进度条拖拽
> 图标、分享卡片吉祥物、额外装饰层（layers）暂时都还是只显示第一帧（静态），以后可能会扩展。

### 可点击切换的动作 actions（可选）——点一下装饰图标，换个姿势（甚至换个动法）

跟上面的 `frames` 不是一回事：`frames` 是自动循环播放，`actions` 是**用户主动点一下装饰图标**才切换，
绕完一圈回到""动作 0""（也就是上面这份 `rows`/`frames`，永远排第一个，不用取名字）。

- `actions`：一个数组，每一项是一个对象：
  - `name`：可选，字符串，纯粹给人看（不参与渲染逻辑），画板里的""动作""选择器会显示这个名字。
  - `frames`：必填，一份帧列表，形状规则跟上面 icon.frames 完全一样（数组的数组，所有帧同尺寸、
    行数/宽度在 4~64、每行等宽）——**哪怕这个动作只想要 1 帧也要包一层**，写成 `[[...]]`，
    这里没有 `rows` 那种单帧简写。
  - `frameDuration`：可选，数字（秒），不填就落回上面 icon 顶层的 `frameDuration`（再没有就是
    默认的 0.25）。
  - `animation`：可选，这个动作自己的移动方式，形状跟下面「动画 animation」完全一样
    （`type`/`duration`/`musicReactive`/`sensitivity`，**包括 `drift`/`fall`/`walk`**）。
    **不填就沿用 icon 顶层的 `animation`**，这是这个字段加进来之前唯一的行为；填了的话是一份
    完整独立的配置，不是往顶层动画上打补丁——`duration`/`musicReactive`/`sensitivity` 各自用
    自己的默认值，不会继承顶层那份的对应字段。点到一个把 `type` 写成 `drift`/`fall`/`walk`
    的动作，图标会真的搬进对应的专属渲染结构（飘过/飘落卡片的三重影轨道，或者装饰栏里来回走）；
    再点回一个用普通招式（或者沿用顶层）的动作，又会搬回固定的装饰栏位置——顶层选的是哪招跟每个
    动作各自选的是哪招完全独立，互不限制。唯一的规则：`drift`/`fall`/`walk` 不能跟别的招式组合
    （也不能互相组合），跟顶层 `animation` 的组合规则一模一样，只能单独出现，比如 `""walk""`
    而不是 `""walk+sway""`。
  - `autoSwitchAfterSeconds`：可选，数字（秒），必须大于 0。**数据驱动的自动切换**——不用等用户点，
    当前正在播的这首歌""连续播放""（暂停不计时，切下一首歌就清零重新计）满这么多秒之后，自动切到
    这个动作。多个动作都设了这个字段的话，取""秒数已经够了的里面这个数字最大""的那个（数字越大代表
    越靠后才该出现的阶段，不是看它在数组里排第几个）；已经手动点到（或者已经被自动切到）更靠后的
    动作时不会被拉回来——只会把动作往前推，不会跟已经做出的选择打架。不填就是这个字段加进来之前
    唯一的行为：完全靠点击手动切换。
  - `transitionSeconds`：可选，数字（秒），必须大于 0。切到这个动作不再是瞬间跳变，而是花这么多秒
    把切换前正显示的画面透明度慢慢淡化掉，露出这个动作已经在播的新画面（新画面从一开始就正常播放，
    不是等淡化完才开始动）。**只在切换前后待在同一条移动轨道时才生效**——普通装饰栏里的招式
    （`pulse`/`twinkle`/`bob`/`sway`/`spin`/`flicker`/组合，或者不写 `animation`）算一条轨道，
    `walk` 来回走算另一条，两条轨道之间互相切换、以及 `drift`/`fall`（三重影）暂时都还是瞬间切换，
    填了这个字段也不报错，只是不生效。不填就是这个字段加进来之前唯一的行为：瞬间切换。
- 最多 10 个（不算动作 0）。所有动作共用 icon 顶层同一份 `palette`——用到的字符记得都在
  `palette` 里配上颜色，动作专属的颜色也不例外。
- 目前**只有主图标**响应点击切换动作（跟 frames 的限制一样：Mini 小方块、额外装饰层 layers
  暂时都不支持，点了没反应）——`autoSwitchAfterSeconds` 同理，只对主图标的动作有意义。

示例（默认站姿是 `sway` 轻摆，""挥手""动作换了张脸还带自己的 `spin` 转圈，点一下切过去，
