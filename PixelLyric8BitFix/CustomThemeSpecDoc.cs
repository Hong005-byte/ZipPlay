## 颜色 colors

全部是 #RRGGBB 或带透明度的 #AARRGGBB 格式（比如 #F9C784、#B32A1F40）。

| 字段 | 必填 | 说明 |
|---|---|---|
| `title` | 是 | 歌曲标题文字颜色 |
| `artist` | 是 | 艺人名 / 时间文字颜色 |
