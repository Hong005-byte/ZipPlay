## 动画 animation

`type` 是这几种之一，也可以用 **+** 连起来同时挂好几招（比如 ""pulse+sway""）：

| 招式 | 效果 |
|---|---|
| `pulse` | 呼吸发光，平缓的明暗循环 |
| `twinkle` | 图标本体渐隐渐现，比 pulse 幅度更大 |
| `drift` | 飘过整张卡片（横向，三张重影同时飘，飘到头瞬间重置回起点） |
| `fall` | 飘落整张卡片（纵向，带一点左右摇摆，同样是三张重影） |
| `walk` | 在顶部装饰栏那条窄带里**来回走**（单张图标，走到边缘转身走回来，不是消失重出现），
  跟 Minecraft 皮肤 Steve 走路同一套手法，固定在较高的显示层级，不会被歌词内容挡住 |
| `bob` | 原地上下浮动 |
| `sway` | 以底部为轴心左右轻摆 |
| `spin` | 匀速转圈 |
| `flicker` | 不规则明暗跳动，比 pulse/twinkle 更""毛躁"" |

**组合规则**：

- 两招控制的是同一个属性的话，后一个会直接盖掉前一个，等于只有后一个生效——不是报错，是""选了也
  白选""。哪几招是同一属性：`pulse`/`flicker` 都是控制发光度；`sway`/`spin` 都是控制角度；
  `bob`/`fall` 都是控制纵向位置。挑组合的时候尽量选控制不同属性的招式，才能真的叠加出效果
  （比如 pulse+sway、twinkle+bob+spin）。
- **drift/fall/walk 不能跟别的招式组合，也不能互相组合**——这三招各自要用专属的渲染结构（drift/
  fall 是整张卡片飘过/飘落的三重影轨道，walk 是装饰栏里来回走的单独图标），跟主图标固定显示在
  装饰栏这件事结构上冲突，只能单独用（比如 ""drift"" 或 ""walk""，不能是 ""drift+pulse"" 或
  ""walk+sway""）。**这条限制只对主图标（顶层 animation）生效，layers 里的额外装饰层没有这个
  限制，可以自由组合全部 9 招**（drift/walk 在层里会退化成同一种原地水平小幅摆动，因为层没有
  三重影轨道也没有独立的装饰带可以横穿）。

其它字段：

| 字段 | 必填 | 说明 |
|---|---|---|
| `duration` | 否 | 秒，数字，必须大于 0；不填就用每种招式各自的默认时长 |
| `musicReactive` | 否 | true/false，不填默认 false。开了之后，这份动画（不管选的是哪招/哪个组合）的播放速度会跟着系统正在播的音乐响度/鼓点实时变化，跟设置页「皮肤音乐律动」总开关是同一套机制，那个开关关了这里勾了也不生效 |
| `sensitivity` | 否 | ""low"" / ""medium"" / ""high""，不填默认 medium。只在 musicReactive 为 true 时才有意义，决定这份动画对响度/鼓点变化""反应多强""——low 声音大变化也比较克制，high 反过来会被小声音放得更明显 |

## 额外装饰层 layers（可选，最多 2 个）

数组，每个元素是一个对象：

| 字段 | 必填 | 说明 |
|---|---|---|
| `anchor` | 是 | 贴在卡片哪个角：""top-left"" / ""top-right"" / ""bottom-left"" / ""bottom-right"" |
| `icon` | 是 | 跟主图标同一套字段形状（rows + palette） |
| `animation` | 是 | 跟主图标同一套字段形状，**但没有""drift/fall 不能组合""这条限制** |

