## 顶层字段

| 字段 | 必填 | 类型 | 说明 |
|---|---|---|---|
| `name` | 是 | 字符串 | 主题名字，显示在皮肤选择器和「已保存的客制化主题」列表里 |
| `font` | 否 | 字符串 | 字体名，系统里得真的装了这个字体（不填默认 `Segoe UI`）；内置皮肤常用的几款：`Segoe UI` / `Segoe UI Light` / `Segoe UI Semibold` / `Georgia` / `Consolas` / `Lucida Console`，这几个 Windows 都自带 |
| `colors` | 是 | 对象 | 见下面「颜色」 |
| `background` | 是 | 对象 | 见下面「背景」 |
| `icon` | 是 | 对象 | 见下面「图标」（主图标，固定贴在歌词框上方那条装饰栏） |
| `animation` | 是 | 对象 | 见下面「动画」 |
